# 兜底判定用的「赛道信号词」：职位名看不出赛道时，要求 JD 正文里确实有足够信号。
# 不加这道门槛的话，猎聘按「区块链」关键词返回的 CMO、大客户总监、银行 BD
# 会被整片算成「Web3 技术岗」，把赛道结论带偏。
TRACK_SIGNALS: dict[Track, str] = {
    WEB3: r"区块链|blockchain|web3|智能合约|链上|数字货币|加密货币|虚拟资产|钱包|"
          r"交易所|defi|以太坊|比特币|稳定币|通证|\brwa\b",
    SEC: r"安全|漏洞|渗透|攻防|逆向|风控|合规审计|加固|反作弊|威胁",
    AI: r"大模型|\bllm\b|人工智能|机器学习|深度学习|算法|智能体|\bagent\b|\baigc?\b|模型训练",
}
SIGNAL_MIN = 3  # JD 正文里至少出现这么多次才算「真的属于这条赛道」
STRONG_SIGNAL = 6  # 通用职位名（后端/架构师/CTO）被正文改判所需的信号强度


def signal_count(text: str, track: Track) -> int:
    """JD 正文里某条赛道的信号词出现次数。"""
    pattern = TRACK_SIGNALS.get(track)
    return len(re.findall(pattern, text, re.I)) if pattern else 0
